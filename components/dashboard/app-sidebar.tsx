interface AppSidebarProps {
  currentUser: CurrentUser | null
  role: string
  side?: "right" | "left" | undefined
}

export function AppSidebar({
  currentUser,
  role,
  side,
  ...props
}: React.ComponentProps<typeof Sidebar> & AppSidebarProps) {
  
  const user = {
    name: currentUser?.first_name || currentUser?.last_name || "Guest",
    email: currentUser?.email || "you@domain.com",
    avatar: currentUser?.profile_image || "/images/avatar.jpg",
  }

  // 1. تحديد القائمة الأساسية بناءً على الدور
  const baseMenu =
    role === "admin"
      ? appConfig.menu.dashboard.adminMenu
      : appConfig.menu.dashboard.customerMenu

  // 2. دمج القائمة الأساسية مع بيانات المستخدم لإنشاء الكائن النهائي
  const data = {
    ...baseMenu,
    user,
  }

  return (
    <Sidebar collapsible="icon" {...props} side={side}>
      <SidebarHeader>
        <TeamSwitcher teams={data.teams} />
      </SidebarHeader>
      <SidebarContent>
        <NavMain items={data.navMain} />
        {/* <NavProjects projects={data.projects} /> */}
      </SidebarContent>
      <SidebarFooter>
        <NavUser user={data.user} />
      </SidebarFooter>
      <SidebarRail />
    </Sidebar>
  )
}
